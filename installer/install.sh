# --- Pre-flight checks ---

check_root() {
    if [ "$(id -u)" -ne 0 ]; then
        fatal "This script must be run as root. Try: sudo bash or curl ... | sudo bash"
    fi
}

check_systemd() {
    if ! command -v systemctl &>/dev/null; then
        fatal "systemd is required but not found. This script does not support init.d or other init systems."
    fi
}

check_curl_or_wget() {
    if command -v curl &>/dev/null; then
        DOWNLOADER="curl"
    elif command -v wget &>/dev/null; then
        DOWNLOADER="wget"
    else
        error "curl or wget is required but neither was found."
        error "On Debian/Ubuntu: sudo apt-get install -y curl ca-certificates"
        error "On Fedora/RHEL:   sudo dnf install -y curl ca-certificates"
        error "On Arch:          sudo pacman -S curl ca-certificates"
        exit 1
    fi
}

# --- Platform detection ---

detect_arch() {
    local arch
    arch=$(uname -m)
    case "$arch" in
        x86_64|amd64)  ARCH="amd64" ;;
        aarch64|arm64) ARCH="arm64" ;;
        *) fatal "Unsupported architecture: $arch. OpenAVC supports x86_64 and arm64." ;;
    esac
    ok "Architecture: $ARCH"
}

detect_distro() {
    if [ -f /etc/os-release ]; then
        . /etc/os-release
        DISTRO_ID="${ID:-unknown}"
        DISTRO_ID_LIKE="${ID_LIKE:-}"
        DISTRO_NAME="${PRETTY_NAME:-$DISTRO_ID}"
    else
        fatal "Cannot detect Linux distribution (/etc/os-release not found)."
    fi

    # Determine package manager
    if command -v apt-get &>/dev/null; then
        PKG_MANAGER="apt"
    elif command -v dnf &>/dev/null; then
        PKG_MANAGER="dnf"
    elif command -v pacman &>/dev/null; then
        PKG_MANAGER="pacman"
    else
        fatal "No supported package manager found (apt, dnf, or pacman required)."
    fi

    ok "Distribution: $DISTRO_NAME (package manager: $PKG_MANAGER)"
}

# --- Python ---

python_version_ok() {
    local python_bin="$1"
    if ! command -v "$python_bin" &>/dev/null; then
        return 1
    fi
    local version
    version=$("$python_bin" -c "import sys; print(f'{sys.version_info.major}.{sys.version_info.minor}')" 2>/dev/null) || return 1
    local major minor
    major=$(echo "$version" | cut -d. -f1)
    minor=$(echo "$version" | cut -d. -f2)
    if [ "$major" -gt "$MIN_PYTHON_MAJOR" ] || { [ "$major" -eq "$MIN_PYTHON_MAJOR" ] && [ "$minor" -ge "$MIN_PYTHON_MINOR" ]; }; then
        return 0
    fi
    return 1
}

find_python() {
    # Check common Python binary names
    for py in python3.13 python3.12 python3.11 python3; do
        if python_version_ok "$py"; then
            PYTHON_BIN=$(command -v "$py")
            ok "Python: $($PYTHON_BIN --version) at $PYTHON_BIN"
            return 0
        fi
    done
    return 1
}

install_python() {
    info "Installing Python ${MIN_PYTHON_MAJOR}.${MIN_PYTHON_MINOR}+ and system prerequisites..."

    case "$PKG_MANAGER" in
        apt)
            # Try system Python first, then deadsnakes PPA for older Ubuntu.
            # ca-certificates + tar are pulled in defensively for minimal images
            # (cloud Ubuntu, slim containers) that don't include them.
            apt-get update -qq
            if apt-cache show python3 2>/dev/null | grep -qE "Version: 3\.(1[1-9]|[2-9][0-9])"; then
                apt-get install -y -qq python3 python3-venv python3-pip ca-certificates tar
            else
                info "System Python is too old. Adding deadsnakes PPA..."
                apt-get install -y -qq software-properties-common ca-certificates tar
                add-apt-repository -y ppa:deadsnakes/ppa
                apt-get update -qq
                apt-get install -y -qq python3.12 python3.12-venv
            fi
            ;;
        dnf)
            dnf install -y -q python3 python3-pip ca-certificates tar
            ;;
        pacman)
            pacman -Sy --noconfirm --quiet python python-pip ca-certificates tar
            ;;
    esac

    if ! find_python; then
        fatal "Failed to install Python ${MIN_PYTHON_MAJOR}.${MIN_PYTHON_MINOR}+. Please install it manually and re-run this script."
    fi
}

ensure_python() {
    if find_python; then
        ensure_venv_module
        return 0
    fi
    install_python
}

# A server can have Python without its venv module: Ubuntu Server and cloud
# images ship python3 but not python3-venv, and Debian splits it out the same
# way. find_python only checks the version, so without this the install got as
# far as extracting the release and then failed creating the environment.
ensure_venv_module() {
    if "$PYTHON_BIN" -c "import ensurepip, venv" &>/dev/null; then
        return 0
    fi
    local ver
    ver=$("$PYTHON_BIN" -c "import sys; print(f'{sys.version_info.major}.{sys.version_info.minor}')")
    case "$PKG_MANAGER" in
        apt)
            info "Installing the Python ${ver} venv module..."
            apt-get update -qq
            apt-get install -y -qq "python${ver}-venv" || apt-get install -y -qq python3-venv
            ;;
    esac
    if ! "$PYTHON_BIN" -c "import ensurepip, venv" &>/dev/null; then
        fatal "Python ${ver} cannot create a virtual environment. Install its venv package (on Debian/Ubuntu: sudo apt-get install python${ver}-venv) and re-run this script."
    fi
    ok "Python venv module ready"
}

# Ensure ca-certificates + tar are present even when Python is already
# installed. Minimal cloud / container Ubuntu images sometimes ship Python
# but no CA bundle, which causes confusing TLS errors on the GitHub
# download below rather than a clean "missing dependency" message.
ensure_system_prereqs() {
    case "$PKG_MANAGER" in
        apt)
            if ! dpkg -s ca-certificates &>/dev/null || ! command -v tar &>/dev/null; then
                info "Installing system prerequisites (ca-certificates, tar)..."
                apt-get update -qq
                apt-get install -y -qq ca-certificates tar
            fi
            ;;
        dnf)
            if ! rpm -q ca-certificates &>/dev/null || ! command -v tar &>/dev/null; then
                info "Installing system prerequisites (ca-certificates, tar)..."
                dnf install -y -q ca-certificates tar
            fi
            ;;
        pacman)
            if ! pacman -Qi ca-certificates &>/dev/null || ! command -v tar &>/dev/null; then
                info "Installing system prerequisites (ca-certificates, tar)..."
                pacman -Sy --noconfirm --quiet ca-certificates tar
            fi
            ;;
    esac
    ensure_ssh_client
}

# The SSH transport runs the system's ssh program (switches, video bars and
# other devices controlled over SSH). Most hosts have it; minimal and container
# images do not. Package names per manager are in openavc/system/os_programs.py.
# Never fatal: OpenAVC runs without it, and the device card says how to add it.
ensure_ssh_client() {
    if command -v ssh &>/dev/null; then
        return 0
    fi
    info "Installing the SSH client (for devices controlled over SSH)..."
    local installed=1
    case "$PKG_MANAGER" in
        apt)
            apt-get update -qq && apt-get install -y -qq openssh-client && installed=0 ;;
        dnf)
            dnf install -y -q openssh-clients && installed=0 ;;
        pacman)
            pacman -Sy --noconfirm --quiet openssh && installed=0 ;;
    esac
    if [ "$installed" -ne 0 ]; then
        warn "Could not install the SSH client. Devices controlled over SSH will not connect until it is installed."
    fi
    return 0
}

# --- Download ---

download() {
    local url="$1"
    local dest="$2"
    if [ "$DOWNLOADER" = "curl" ]; then
        curl -fsSL -o "$dest" "$url"
    else
        wget -q -O "$dest" "$url"
    fi
}

get_latest_release_url() {
    local asset_name="openavc-.*-linux-${ARCH}\\.tar\\.gz"

    info "Checking for latest release..."

    # Try /releases/latest first (stable releases only), then fall back to
    # /releases (includes prereleases) so beta testers can install too.
    local release_json=""
    local api_urls=(
        "https://api.github.com/repos/${GITHUB_REPO}/releases/latest"
        "https://api.github.com/repos/${GITHUB_REPO}/releases?per_page=1"
    )

    for api_url in "${api_urls[@]}"; do
        if [ "$DOWNLOADER" = "curl" ]; then
            release_json=$(curl -fsSL -H "Accept: application/vnd.github.v3+json" "$api_url" 2>/dev/null) || true
        else
            release_json=$(wget -q -O - --header="Accept: application/vnd.github.v3+json" "$api_url" 2>/dev/null) || true
        fi

        if [ -n "$release_json" ]; then
            break
        fi
    done

    if [ -z "$release_json" ]; then
        return 1
    fi

    # Parse JSON without jq (grep + sed)
    RELEASE_VERSION=$(echo "$release_json" | grep -o '"tag_name":\s*"[^"]*"' | head -1 | sed 's/.*"tag_name":\s*"\([^"]*\)".*/\1/' | sed 's/^v//')
    RELEASE_URL=$(echo "$release_json" | grep -o '"browser_download_url":\s*"[^"]*linux-'"${ARCH}"'[^"]*\.tar\.gz"' | head -1 | sed 's/"browser_download_url":\s*"\([^"]*\)"/\1/')
    CHECKSUMS_URL=$(echo "$release_json" | grep -o '"browser_download_url":\s*"[^"]*SHA256SUMS\.txt"' | head -1 | sed 's/"browser_download_url":\s*"\([^"]*\)"/\1/')
    CHECKSUMS_SIG_URL=$(echo "$release_json" | grep -o '"browser_download_url":\s*"[^"]*SHA256SUMS\.txt\.sig"' | head -1 | sed 's/"browser_download_url":\s*"\([^"]*\)"/\1/')

    if [ -n "$RELEASE_URL" ] && [ -n "$RELEASE_VERSION" ]; then
        ok "Latest release: v${RELEASE_VERSION}"
        return 0
    fi

    return 1
}

# Verify SHA256SUMS.txt's detached signature against the embedded trusted key
# before trusting any hash in it. Without this, an attacker who can replace a
# release asset could swap the tarball AND its SHA256SUMS.txt consistently and
# still pass the checksum check. Fail-closed once signing is armed; skipped with
# a warning while the key is empty (checksum-only, matching prior behavior).
verify_checksums_signature() {
    local sums_file="$1"

    if [ -z "$TRUSTED_SIGNING_PUBKEY" ]; then
        warn "Release signing not yet armed — verifying checksum only (no signature)."
        return 0
    fi
    if ! command -v openssl &>/dev/null; then
        fatal "openssl not found but release signing is armed — cannot verify authenticity. Install openssl and re-run."
    fi
    if [ -z "${CHECKSUMS_SIG_URL:-}" ]; then
        fatal "No SHA256SUMS.txt.sig in the release assets — refusing to install (release signing is armed)."
    fi

    local sig_file="/tmp/openavc-SHA256SUMS.txt.sig"
    local key_file="/tmp/openavc-release-pubkey.pem"
    if ! download "$CHECKSUMS_SIG_URL" "$sig_file"; then
        fatal "Failed to download SHA256SUMS.txt.sig — refusing unverified install."
    fi
    printf '%s\n' "$TRUSTED_SIGNING_PUBKEY" > "$key_file"
    if ! openssl dgst -sha256 -verify "$key_file" -signature "$sig_file" "$sums_file" >/dev/null 2>&1; then
        rm -f "$sig_file" "$key_file"
        fatal "SHA256SUMS.txt signature did not verify against the trusted key — refusing install."
    fi
    rm -f "$sig_file" "$key_file"
    ok "Release signature verified"
}

# Verify the downloaded archive against the release's SHA256SUMS.txt.
# Fail-closed: refuse to install if the checksums file is missing, the
# archive isn't listed, or the hash doesn't match — never install an
# unverified artifact.
verify_checksum() {
    local archive="$1"

    if [ -z "${CHECKSUMS_URL:-}" ]; then
        fatal "No SHA256SUMS.txt in the release assets — refusing to install an unverified download."
    fi
    if ! command -v sha256sum &>/dev/null; then
        fatal "sha256sum not found — cannot verify download integrity. Install coreutils and re-run."
    fi

    local sums_file="/tmp/openavc-SHA256SUMS.txt"
    info "Verifying download integrity..."
    if ! download "$CHECKSUMS_URL" "$sums_file"; then
        fatal "Failed to download SHA256SUMS.txt — refusing to install unverified."
    fi

    # Authenticate the checksums file itself before trusting any hash in it.
    verify_checksums_signature "$sums_file"

    local artifact_name expected actual
    artifact_name=$(basename "$archive")
    # Field 2 is the filename (strip the optional binary-mode '*'); print the
    # matching hash from field 1. Mirrors the in-app verifier's parser.
    expected=$(awk -v name="$artifact_name" '{ f=$2; sub(/^\*/, "", f); if (f == name) { print $1; exit } }' "$sums_file")
    rm -f "$sums_file"

    if [ -z "$expected" ]; then
        rm -f "$archive"
        fatal "Checksum for ${artifact_name} not found in SHA256SUMS.txt — refusing to install."
    fi

    actual=$(sha256sum "$archive" | awk '{print $1}')
    if [ "$actual" != "$expected" ]; then
        rm -f "$archive"
        fatal "Checksum mismatch for ${artifact_name}: expected ${expected}, got ${actual}. Aborting install."
    fi

    ok "Checksum verified"
}

download_release() {
    if ! get_latest_release_url; then
        fatal "Could not find a release for linux-${ARCH}. Check https://github.com/${GITHUB_REPO}/releases"
    fi

    local archive="/tmp/openavc-${RELEASE_VERSION}-linux-${ARCH}.tar.gz"
    info "Downloading v${RELEASE_VERSION} for linux-${ARCH}..."
    download "$RELEASE_URL" "$archive"
    ok "Downloaded: $(du -h "$archive" | cut -f1)"

    verify_checksum "$archive"

    ARCHIVE_PATH="$archive"
}

# --- Install ---

create_user() {
    if id "$SERVICE_USER" &>/dev/null; then
        ok "User '$SERVICE_USER' already exists"
        return 0
    fi

    info "Creating system user '$SERVICE_USER'..."
    useradd --system --shell /usr/sbin/nologin --home-dir "$INSTALL_DIR" --create-home "$SERVICE_USER"
    ok "Created user: $SERVICE_USER"
}

# Whether $1 holds a release this script can install: the package, and the
# service unit install_service installs from it. What the apply library asks
# of the unpacked release before the running install is moved.
is_installable_release() {
    [ -f "$1/pyproject.toml" ] && [ -d "$1/openavc" ] && [ -f "$1/installer/openavc.service" ]
}

# What the swap carries into the new release: a Linux install's own folders.
# shellcheck disable=SC2034  # read by the apply library
PRESERVE_DIRS=("${LINUX_KEPT_DIRS[@]}")

# Set by install_files: whether it replaced an install, and whether that
# install's service was running when it was stopped for the swap.
IS_UPGRADE=false
WAS_RUNNING=false

# Start the service again on the install that was running, when it was running
# before install_files stopped it.
restart_previous_service() {
    if [ "$WAS_RUNNING" = true ]; then
        systemctl start "$SERVICE_NAME" 2>/dev/null || true
    fi
}

# A step after the swap failed: put the install that was running back in place
# of the new release (the apply library leaves that to the steps after it) and
# start it again. A fresh install has nothing to put back.
put_back_previous_install() {
    [ "$IS_UPGRADE" = true ] || return 0
    local previous="${INSTALL_DIR}.previous"
    if [ -d "$previous" ] && rm -rf "$INSTALL_DIR" && mv "$previous" "$INSTALL_DIR"; then
        info "Put back the install that was running"
        restart_previous_service
    else
        error "Could not put back the install that was running; it is at ${previous}"
    fi
}

install_files() {
    # Both layouts count as an existing install. 0.24.1 and earlier unpacked
    # server/ simulator/ web/ themes/ at the top level; 0.25.0 puts all four
    # inside openavc/. Look for only one of them and the upgrade that matters
    # most -- the one that crosses between them -- reads as a fresh install:
    # no service stop, and no .previous to roll back to.
    if [ -d "$INSTALL_DIR/openavc" ] || [ -d "$INSTALL_DIR/server" ]; then
        IS_UPGRADE=true
        info "Existing installation found. Upgrading..."
        if systemctl is-active --quiet "$SERVICE_NAME" 2>/dev/null; then
            WAS_RUNNING=true
        fi
        systemctl stop "$SERVICE_NAME" 2>/dev/null || true

        # The release goes in as a fresh tree, not written over the install,
        # so nothing a newer release stopped shipping survives beside it: the
        # service runs with WorkingDirectory=$INSTALL_DIR, so a pre-0.25.0
        # server/ left there would be imported by a driver still saying
        # `from server.…` as a whole second copy of the platform, instead of
        # that driver failing with the message that says to update it.
        info "Installing to ${INSTALL_DIR}/..."
        if ! apply_release "$ARCHIVE_PATH" "$INSTALL_DIR" "" is_installable_release; then
            rm -f "$ARCHIVE_PATH"
            restart_previous_service
            fatal "This release could not be installed, so OpenAVC was left on the version it had. The reason is above; once it is fixed, run this installer again."
        fi
        ok "Installed to ${INSTALL_DIR}/ (the version it replaced is kept at ${INSTALL_DIR}.previous)"
    else
        info "Extracting to ${INSTALL_DIR}/..."
        mkdir -p "$INSTALL_DIR"
        tar -xzf "$ARCHIVE_PATH" -C "$INSTALL_DIR"
        ok "Extracted to ${INSTALL_DIR}/"
    fi

    # Place update helper script where systemd ExecStartPre expects it
    if [ -f "$INSTALL_DIR/installer/update-helper.sh" ]; then
        cp "$INSTALL_DIR/installer/update-helper.sh" "$INSTALL_DIR/update-helper.sh"
        chmod 755 "$INSTALL_DIR/update-helper.sh"
        ok "Update helper installed"
    fi

    # Firewall sync helper (ExecStartPre): keeps ufw/firewalld in step with
    # the configured listeners on every service start, so enabling HTTPS or
    # Short URLs in Settings opens the port without manual firewall edits.
    if [ -f "$INSTALL_DIR/installer/firewall-sync.sh" ]; then
        cp "$INSTALL_DIR/installer/firewall-sync.sh" "$INSTALL_DIR/firewall-sync.sh"
        chmod 755 "$INSTALL_DIR/firewall-sync.sh"
        ok "Firewall sync helper installed"
    fi

    # Clean up archive
    rm -f "$ARCHIVE_PATH"
}

# The Python environment, carried across from the install it replaced or made
# new, with the release's requirements installed into it.
make_venv() {
    if [ -d "$INSTALL_DIR/venv" ]; then
        "$PYTHON_BIN" -m venv --upgrade "$INSTALL_DIR/venv" || return 1
    else
        "$PYTHON_BIN" -m venv "$INSTALL_DIR/venv" || return 1
    fi
    "$INSTALL_DIR/venv/bin/pip" install --quiet --upgrade pip || return 1
    "$INSTALL_DIR/venv/bin/pip" install --quiet -r "$INSTALL_DIR/requirements.txt" || return 1
}

create_venv() {
    info "Setting up Python virtual environment..."
    # A new release whose packages are missing would crash on its first
    # import at every start, so an upgrade that cannot install them goes back
    # to the install it replaced.
    if ! make_venv; then
        if [ "$IS_UPGRADE" = true ]; then
            put_back_previous_install
            fatal "The release's Python packages could not be installed, so OpenAVC was left on the version it had. Check that this computer can reach pypi.org, then run this installer again."
        fi
        fatal "OpenAVC's Python packages could not be installed. Check that this computer can reach pypi.org, then run this installer again."
    fi
    ok "Virtual environment ready"
}

setup_data_dir() {
    info "Setting up data directory at ${DATA_DIR}/..."

    mkdir -p "$DATA_DIR"/{projects/default,backups,logs}
    mkdir -p "$LOG_DIR"

    # Seed default project if not present. The starter project ships inside
    # the package; a release from before that keeps it under installer/seed/.
    if [ ! -f "$DATA_DIR/projects/default/project.avc" ]; then
        for seed in "$INSTALL_DIR/openavc/seed/default/project.avc" \
                    "$INSTALL_DIR/installer/seed/default/project.avc"; do
            if [ -f "$seed" ]; then
                cp "$seed" "$DATA_DIR/projects/default/project.avc"
                info "Seeded default project"
                break
            fi
        done
    fi

    # Set ownership
    chown -R "$SERVICE_USER:$SERVICE_GROUP" "$DATA_DIR"
    chown -R "$SERVICE_USER:$SERVICE_GROUP" "$LOG_DIR"
    chown -R "$SERVICE_USER:$SERVICE_GROUP" "$INSTALL_DIR"

    # The recursive chown above just made the signing-key store and the
    # root-executed helpers writable by the service user. Re-assert root
    # ownership on them so a compromised openavc process can't swap in its own
    # key or rewrite the helper root runs (the update-signing trust root). Mirrors
    # update-helper.sh's harden_privileged_paths.
    harden_trust_store

    ok "Data directory ready"
}

# Keep the signing-key store + the root-executed scripts root-owned and
# unreachable-for-write by the service user. Owning a parent directory is enough
# to rename/replace a root-owned child, so $INSTALL_DIR and installer/ are rooted
# too; venv/server and the rest stay openavc-owned. No-op until a key ships.
harden_trust_store() {
    local keys_dir="$INSTALL_DIR/installer/trusted-keys"
    [ -d "$keys_dir" ] || return 0
    chown root:root "$INSTALL_DIR" 2>/dev/null || true
    chown -R root:root "$INSTALL_DIR/installer" 2>/dev/null || true
    chown root:root "$INSTALL_DIR/update-helper.sh" "$INSTALL_DIR/firewall-sync.sh" 2>/dev/null || true
    chmod 755 "$INSTALL_DIR" "$INSTALL_DIR/installer" "$keys_dir" 2>/dev/null || true
    chmod 644 "$keys_dir"/*.pem 2>/dev/null || true
}

install_service() {
    info "Installing systemd service..."

    # The unit the release ships, made for this host by the apply library, as
    # the update helper makes it at every start: on a host that cannot grant
    # CAP_NET_RAW its AmbientCapabilities line, which would stop systemd
    # starting the service, is left out.
    local shipped="$INSTALL_DIR/installer/openavc.service"
    if [ ! -f "$shipped" ]; then
        fatal "This release has no installer/openavc.service, so it cannot be installed as a service."
    fi
    host_unit "$shipped" "$SERVICE_FILE" || fatal "Could not write ${SERVICE_FILE}."
    chmod 644 "$SERVICE_FILE"

    if ! host_has_cap_net_raw; then
        warn "CAP_NET_RAW is not in this host's capability bounding set (a container started with it dropped)."
        warn "Disabling it in the service so OpenAVC still starts. The discovery ping sweep will be limited;"
        warn "passive discovery (mDNS/SSDP) and adding devices by IP still work."
    fi

    systemctl daemon-reload
    systemctl enable "$SERVICE_NAME"
    ok "Service installed and enabled"
}

configure_firewall() {
    # One source of truth: the same helper that runs at every service start
    # (ExecStartPre) syncs ufw/firewalld with the configured listeners — the
    # HTTP port, the HTTPS port when TLS is on, and port 80 when Short URLs
    # are on. Running it here just opens the ports before the first start.
    # It no-ops when neither ufw nor firewalld is active.
    if [ -x "$INSTALL_DIR/firewall-sync.sh" ]; then
        info "Syncing firewall with configured ports..."
        "$INSTALL_DIR/firewall-sync.sh" "$DATA_DIR"
        ok "Firewall synced (ufw/firewalld if active; ports follow Settings from now on)"
    else
        warn "Firewall sync helper missing; if ufw/firewalld is active, allow port $HTTP_PORT/tcp manually."
    fi
}

# Remove the legacy /opt/openavc/{driver,plugin}_repo dirs once they're drained.
# These predate user content moving to the data dir. The runtime migration
# (openavc/system_config.migrate_legacy_repos) empties them on first start, but
# leaves the empty dir behind — and the service unit keeps it writable via
# ReadWritePaths, which makes systemd bind-mount it. An in-app update then fails
# (EBUSY) trying to mv that mountpoint. Re-running the installer is the escape
# path for such boxes, so drop the empty dirs here. Only remove them when empty
# (rmdir refuses non-empty); a box with un-drained content keeps them until the
# next server start drains them, then a later installer run clears them.
cleanup_legacy_repos() {
    local dir
    for dir in "$INSTALL_DIR/driver_repo" "$INSTALL_DIR/plugin_repo"; do
        if [ -d "$dir" ] && rmdir "$dir" 2>/dev/null; then
            info "Removed drained legacy repo dir: $dir"
        fi
    done
}

start_service() {
    info "Starting OpenAVC..."
    systemctl start "$SERVICE_NAME"

    # Wait a moment and check if it's running
    sleep 3
    if systemctl is-active --quiet "$SERVICE_NAME"; then
        ok "OpenAVC is running"
    else
        error "OpenAVC failed to start. Check: journalctl -u $SERVICE_NAME -n 50"
        return 1
    fi
}

# --- Main ---

main() {
    echo ""
    echo -e "${GREEN}============================================================${NC}"
    echo -e "${GREEN}  OpenAVC Linux Installer${NC}"
    echo -e "${GREEN}============================================================${NC}"
    echo ""

    check_root
    check_systemd
    check_curl_or_wget

    detect_arch
    detect_distro
    ensure_system_prereqs
    ensure_python

    download_release
    create_user
    install_files
    create_venv
    setup_data_dir
    cleanup_legacy_repos
    install_service
    configure_firewall
    start_service

    # Get the server's IP address for the URL
    local ip
    ip=$(hostname -I 2>/dev/null | awk '{print $1}')
    if [ -z "$ip" ]; then
        ip="<your-server-ip>"
    fi

    echo ""
    echo -e "${GREEN}============================================================${NC}"
    echo -e "${GREEN}  OpenAVC v${RELEASE_VERSION} installed successfully!${NC}"
    echo -e "${GREEN}============================================================${NC}"
    echo ""
    echo -e "  Programmer IDE:  ${BLUE}http://${ip}:${HTTP_PORT}/programmer${NC}"
    echo -e "  Panel UI:        ${BLUE}http://${ip}:${HTTP_PORT}/panel${NC}"
    echo -e "  REST API:        ${BLUE}http://${ip}:${HTTP_PORT}/api${NC}"
    echo ""
    echo -e "  Service:         systemctl {start|stop|restart|status} $SERVICE_NAME"
    echo -e "  Logs:            journalctl -u $SERVICE_NAME -f"
    echo -e "  Data:            $DATA_DIR/"
    echo ""
    echo -e "  To upgrade later, re-run this script."
    echo ""
}

main "$@"
