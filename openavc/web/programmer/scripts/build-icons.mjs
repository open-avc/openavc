// Copies the lucide-static sprite to the panel runtime (openavc/web/panel/icons.svg)
// and regenerates spriteIconNames.ts from its symbol ids, so the icon picker
// can only offer names the panel can actually render. The panel resolves
// icons by direct sprite lookup (icons.svg#<name>); deriving the picker list
// from anything else (e.g. lucide-react's PascalCase exports) drifts from the
// sprite ids. Runs as part of `npm run build`.
//
// It also writes the panel's table of Lucide's old names (home, tv-2, unlock)
// to the sprite id each now has (openavc/web/panel/modules/icon_aliases.gen.js).
// The sprite carries only current names, while the UI Builder previews through
// lucide-react, which still exports the old ones: a control saved with an old
// name showed its icon in the Builder and drew nothing on the panel. The table
// is read from lucide-react's own alias files (icons/<old>.js re-exporting
// icons/<new>.js), so the panel draws exactly what the Builder shows.
//
// Both page reviews warn on an icon name the panel draws nothing for, so the
// old names also go to spriteIconNames.ts (OLD_ICON_NAMES) for the Builder's,
// and every name the panel draws to openavc/ui/panel_icon_names.py for the AI's.
import { copyFileSync, existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const programmerRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const spritePath = path.join(programmerRoot, "node_modules", "lucide-static", "sprite.svg");
const sprite = readFileSync(spritePath, "utf8");

const names = [...sprite.matchAll(/<symbol[^>]*\bid="([^"]+)"/g)].map((m) => m[1]).sort();
if (names.length < 500) {
  throw new Error(`only ${names.length} symbol ids found in ${spritePath} — sprite format changed?`);
}

copyFileSync(spritePath, path.join(programmerRoot, "..", "panel", "icons.svg"));

const spriteIds = new Set(names);
const reactIcons = path.join(programmerRoot, "node_modules", "lucide-react", "dist", "esm", "icons");
const aliases = {};
for (const file of readdirSync(reactIcons).filter((f) => f.endsWith(".js")).sort()) {
  const old = file.slice(0, -3);
  const target = readFileSync(path.join(reactIcons, file), "utf8")
    .match(/export \{ default \} from '\.\/([^']+)\.js';/)?.[1];
  if (target && !spriteIds.has(old) && spriteIds.has(target)) aliases[old] = target;
}
if (aliases.home !== "house") {
  throw new Error(`lucide-react's alias files no longer map home to house in ${reactIcons} — format changed?`);
}
const aliasPath = path.join(programmerRoot, "..", "panel", "modules", "icon_aliases.gen.js");
const aliasHeader =
  "// Generated by openavc/web/programmer/scripts/build-icons.mjs from lucide-react's\n" +
  "// alias files — do not edit. Each old Lucide icon name the UI Builder still\n" +
  "// previews, and the sprite id (icons.svg) the panel draws it as.\n";
writeFileSync(
  aliasPath,
  `${aliasHeader}export const ICON_ALIASES = Object.freeze(${JSON.stringify(aliases, null, 4)});\n`,
);
const oldNames = Object.keys(aliases);
const outPath = path.join(
  programmerRoot, "src", "components", "ui-builder", "spriteIconNames.ts",
);
const header =
  "// Generated by scripts/build-icons.mjs from lucide-static/sprite.svg — do not edit.\n" +
  "// Symbol ids of the sprite the panel runtime renders icons from\n" +
  "// (openavc/web/panel/icons.svg); the icon picker only offers names on this list.\n";
const oldHeader =
  "\n// Lucide's old names the panel also draws, each as the sprite id it has now\n" +
  "// (openavc/web/panel/modules/icon_aliases.gen.js). The page review reads both lists.\n";
writeFileSync(
  outPath,
  `${header}export const SPRITE_ICON_NAMES: string[] = ${JSON.stringify(names, null, 2)};\n` +
    `${oldHeader}export const OLD_ICON_NAMES: string[] = ${JSON.stringify(oldNames, null, 2)};\n`,
);

// The same names for the AI's page review, which runs in Python
// (openavc/ui/review_icons.py). Written only where that package sits beside
// the web folder: the Docker image builds the frontend in a stage that holds
// the web folders alone, and the image takes the list as committed.
const pyDir = path.join(programmerRoot, "..", "..", "ui");
const pyNames = [...names, ...oldNames].sort();
if (existsSync(pyDir)) writeFileSync(
  path.join(pyDir, "panel_icon_names.py"),
  '"""Generated by openavc/web/programmer/scripts/build-icons.mjs -- do not edit.\n\n' +
    "Every icon name the panel draws: the symbol ids of its sprite\n" +
    "(web/panel/icons.svg), and Lucide's old names it draws as one of them\n" +
    '(web/panel/modules/icon_aliases.gen.js).\n"""\n\n' +
    `PANEL_ICON_NAMES = frozenset({\n${pyNames.map((n) => `    ${JSON.stringify(n)},`).join("\n")}\n})\n`,
);
console.log(
  `build-icons: copied sprite and wrote ${names.length} icon names and ${oldNames.length} old names`,
);
