"""Copy installer/apply-lib.sh into installer/install.sh.

A re-run of install.sh over an install replaces it by the apply library's rule,
the one the update helper applies an in-app update by: the release unpacked
beside the install and checked there, the running install kept whole to roll
back to, the folders no release ships carried across, and the service unit
made for the host. install.sh is fetched and run on its own
(``curl -sSL https://get.openavc.com | bash``) with no release beside it, and
the release it installs may be older than the library, so it carries the
library's text between two marker lines instead of reading the file.

This script writes that block from the library; ``tests/test_apply_lib_delivery.py``
fails when the block differs from the library, naming this script.

Usage:
    python scripts/embed_apply_lib.py           # rewrite the block
    python scripts/embed_apply_lib.py --check   # report a stale block, change nothing
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
LIBRARY = REPO_ROOT / "installer" / "apply-lib.sh"
INSTALL_SCRIPT = REPO_ROOT / "installer" / "install.sh"

BEGIN = "# >>> installer/apply-lib.sh (generated by scripts/embed_apply_lib.py; edit that file, never this block)"
END = "# <<< installer/apply-lib.sh"


def _lf(text: str) -> str:
    return text.replace("\r\n", "\n")


def embedded(install_text: str) -> str:
    """The library text install.sh carries between the markers."""
    lines = _lf(install_text).split("\n")
    try:
        start, end = lines.index(BEGIN), lines.index(END)
    except ValueError:
        raise SystemExit(f"{INSTALL_SCRIPT.name} has no '{BEGIN}' ... '{END}' block") from None
    if end < start:
        raise SystemExit(f"{INSTALL_SCRIPT.name}'s library block ends before it begins")
    body = lines[start + 1:end]
    return "\n".join(body) + "\n" if body else ""


def render(install_text: str, library_text: str) -> str:
    """install.sh with its block replaced by ``library_text``, in install.sh's
    own line endings."""
    current = embedded(install_text)
    lf = _lf(install_text)
    head, rest = lf.split(BEGIN + "\n", 1)
    tail = rest[len(current):]
    assert tail.startswith(END + "\n"), "the block parser and render disagree"
    library = _lf(library_text)
    if not library.endswith("\n"):
        library += "\n"
    out = f"{head}{BEGIN}\n{library}{tail}"
    return out.replace("\n", "\r\n") if "\r\n" in install_text else out


def is_current(install_text: str, library_text: str) -> bool:
    return _lf(embedded(install_text)) == _lf(library_text if library_text.endswith("\n") else library_text + "\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="report a stale block and change nothing")
    args = parser.parse_args(argv)

    install_text = INSTALL_SCRIPT.read_text(encoding="utf-8")
    library_text = LIBRARY.read_text(encoding="utf-8")
    if is_current(install_text, library_text):
        print(f"{INSTALL_SCRIPT.relative_to(REPO_ROOT)} carries {LIBRARY.relative_to(REPO_ROOT)} as it is")
        return 0
    if args.check:
        print(
            f"{INSTALL_SCRIPT.relative_to(REPO_ROOT)} carries an older {LIBRARY.relative_to(REPO_ROOT)}; "
            "run: python scripts/embed_apply_lib.py",
            file=sys.stderr,
        )
        return 1
    INSTALL_SCRIPT.write_bytes(render(install_text, library_text).encode("utf-8"))
    print(f"wrote {LIBRARY.relative_to(REPO_ROOT)} into {INSTALL_SCRIPT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
